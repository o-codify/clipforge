/** Explicit translations keep paths, model internals and external errors out of the user conversation. */
export function narrateEvent(raw: string): string | null {
  const text = raw.trim();
  const stages: Record<string,string> = {
    "1": "Начинаю готовить эфир к нарезке: загружаю запись и звук.",
    "2": "Теперь слушаю эфир и распознаю речь. По расшифровке найду содержательные моменты и сделаю субтитры.",
    "3": "Анализирую звук: ищу всплески громкости, активную речь и эмоциональные моменты.",
    "4": "Ищу камеру стримера, чтобы сохранить лицо в вертикальном кадре.",
    "5": "Сопоставляю речь и звук, выбираю разные моменты и начинаю монтаж клипов.",
  };
  const stage = text.match(/^шаг (\d)\/5/);
  if(stage) return stages[stage[1]!] ?? null;
  const download = text.match(/^(аудио|видео): (\d+)%/);
  if(download) { const percent=Number(download[2]); return percent%20===0 ? `Загружаю ${download[1]==="аудио"?"звук":"видео"}: готово ${percent}%.` : null; }
  const spoken=text.match(/распознано\s+([\d.]+)\s*мин/i);
  if(spoken)return `Я уже разобрал ${spoken[1]} минут речи. Продолжаю слушать эфир.`;
  const archive=text.match(/^найдено эфиров: (\d+)/);
  if(archive)return `Проверил архив канала: нашёл ${archive[1]} эфиров. Обновляю их названия, категории и длительность.`;
  if(text.startsWith("архивы канала"))return "Проверяю канал: ищу новые эфиры для обработки.";
  const transcript=text.match(/^фраз (\d+), слов (\d+)/);
  if(transcript)return `Расшифровка готова: ${transcript[1]} фраз, ${transcript[2]} слов. Использую её для отбора моментов и субтитров.`;
  if(text==="расшифровка уже есть")return "Расшифровка уже готова. Использую её повторно и перехожу дальше.";
  if(text==="сигналы уже посчитаны")return "Анализ звука уже сохранён. Повторять его не нужно.";
  const candidates=text.match(/^кандидатов (\d+)/);
  if(candidates)return `Нашёл ${candidates[1]} потенциально интересных моментов. Сравниваю их и убираю повторы.`;
  const feedback=text.match(/^Отбор: .*публичных наблюдений (\d+)/);
  if(feedback)return Number(feedback[1])>=5 ? `Учитываю результаты опубликованных клипов: доступно ${feedback[1]} наблюдений. Сохраняю место и для новых типов моментов.` : "Публичной статистики пока мало. Выбираю моменты по речи и звуку и пробую разные варианты, не делая преждевременных выводов о популярности.";
  const finished=text.match(/^отрендерено (\d+), заменено (\d+), пропущено (\d+)/);
  if(finished)return `Монтаж завершён: создал ${finished[1]} клипов${Number(finished[2])?`, обновил ${finished[2]}`:""}${Number(finished[3])?`, уже готовых или исключённых — ${finished[3]}`:""}. Результаты можно посмотреть прямо из этого сообщения.`;
  const clip=text.match(/^\[(\d+)\/(\d+)\]/);
  if(clip && !text.includes("СБОЙ"))return text.includes("уже есть") ? `Клип ${clip[1]} из ${clip[2]} уже готов — сохраняю его без повторного монтажа.` : `Готов клип ${clip[1]} из ${clip[2]}. Продолжаю монтаж остальных моментов.`;
  if(text.startsWith("рендер в"))return "Начинаю собирать вертикальные видео: добавляю субтитры и оформление.";
  if(text.startsWith("кадров "))return "Закончил анализ звука. Теперь могу сравнить активность на разных участках эфира.";
  if(/^(Сбой:|Ошибка клипа)|СБОЙ/.test(text))return "На этом этапе произошла ошибка. Сохранил подробности для администратора; готовые материалы остаются доступными.";
  if(text.startsWith("остановлено"))return "Остановил задание по запросу. Уже готовые клипы сохранены.";
  if(text.startsWith("камера уже искалась"))return "Положение камеры уже определено. Использую сохранённое кадрирование.";
  return null;
}
